    private void confirmButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_confirmButtonActionPerformed

        String uname = username.getText();
        String newPass = new String(password.getPassword());       
       String reEnterpass = new String(reEnter_passwordField.getText());  


        if (uname.isEmpty() || newPass.isEmpty()) {     
            new customerWarningMessage("<html>Please enter username<br> and new password</html>").setVisible(true);
            return;
        }
          if (!newPass.equals(reEnterpass)) {
        new customerWarningMessage("Passwords do not match!").setVisible(true);
        return;
    }

        try {
            Connection con = DriverManager.getConnection("jdbc:derby://localhost:1527/GameDb", "game", "game");

            String checkSql = "SELECT * FROM PLAYERTABLES WHERE USERNAME = ?";
            PreparedStatement checkPst = con.prepareStatement(checkSql);
            checkPst.setString(1, uname);
            ResultSet rs = checkPst.executeQuery();

            if (rs.next()) {
                String gameName = rs.getString("GAME_NAME");
                String updateSql = "UPDATE PLAYERTABLES SET PASSWORD = ? WHERE USERNAME = ?";
                PreparedStatement updatePst = con.prepareStatement(updateSql);
                updatePst.setString(1, newPass);
                updatePst.setString(2, uname);
                int updated = updatePst.executeUpdate();

                if (updated > 0) {               
                    new customerWarningMessage("<html>Password updated successfully!<br> You can now log in. </html>"+gameName).setVisible(true);
                    dispose();

                } else {
                    new customerWarningMessage("Failed to update password.").setVisible(true);               
                }

                updatePst.close();
            } else {           
                 new customerWarningMessage("Username not found!").setVisible(true);               
            }

            rs.close();
            checkPst.close();
            con.close();

        } catch (SQLException ex) {
            System.out.println("Database error during password reset!");
            ex.printStackTrace();
             new customerWarningMessage("<html>An error occurred while <br>updating the password.</html>").setVisible(true);    

        }

    }//GEN-LAST:event_confirmButtonActionPerformed

